"""
Pydantic Schemas for LLM & Vision-Language Scene Description.
"""

from typing import Optional
from pydantic import BaseModel, Field


class LLMQueryRequest(BaseModel):
    """
    User question or request regarding an uploaded scene image.
    """
    image_id: str
    user_question: Optional[str] = Field(None, description="Optional custom question (e.g., 'Is there a door ahead?')")
    detail_level: str = Field("concise", description="Detail level: 'concise', 'detailed', or 'navigation'")


class LLMSceneResponse(BaseModel):
    """
    Rich scene narration output generated by Vision LLM.
    """
    image_id: str
    narrative_description: str = Field(..., description="Comprehensive scene description optimized for text-to-speech")
    key_hazards: Optional[str] = Field(None, description="Immediate obstacles or safety warnings detected")
    suggested_actions: Optional[str] = Field(None, description="Actionable advice for visually impaired user")
